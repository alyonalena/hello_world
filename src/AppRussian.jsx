function AppRussian() {
  const [ activeEvent, setActiveEvent ] = useState(null)
  const [ modalPositionY, setModalPositionY ] = useState(0)
  const [ modalPositionX, setModalPositionX ] = useState(0)

  const handleCancel = () => setActiveEvent(null)

  const onItemClick = (item, positionY, positionX) => {
    setActiveEvent(item)
    setModalPositionY(positionY)
    setModalPositionX(positionX)
  }

  const minYear = -2400
  const maxYear = 2026
  const range = maxYear - minYear || 1

  return (
    <>
      <div id="App" className="App" style={{ display: 'flex', minHeight: '100vh' }}>
        <div className="erasBlock">
          {
            russianEras.map((item, index) =>  {
              const height = (Math.abs(item.year-item.endYear) / range) * 100
              const position = ((item.year - minYear) / range) * 100

              return (
                <div 
                  key={item.id}
                  className="era"
                  style={{
                    height: `${height}%`,
                    bottom: `${position}%` ,
                    backgroundColor: `#43c8da`,
                    background: 'linear-gradient(to top,rgb(184, 234, 240), #fff)'
                  }}
                >
                  <h3>{item.year < 0 ? `${Math.abs(item.year)} г. до Н.Э.` : `${item.year} г.`}: {item.title}</h3>
                </div>
              )
            }
          )}
        </div>

      <TimelineDemo items={russianRulers} onItemClick={(item, positionY) => onItemClick(item, positionY, 1)} title={'Правители'}/>
      <TimelineDemo items={russianWars} onItemClick={(item, positionY) => onItemClick(item, positionY, 1)} title={'Войны'}/>
      <TimelineDemo items={russianPersonalities} onItemClick={(item, positionY) => onItemClick(item, positionY, 1)} title={'Личности'}/>
      <TimelineDemo items={russianCulturalEvents} onItemClick={(item, positionY) => onItemClick(item, positionY, 1)} title={'Культура'}/>
      <TimelineDemo items={territorialChanges} onItemClick={(item, positionY) => onItemClick(item, positionY, 1)} title={'Территории'}/>
      <TimelineDemo items={russianCapitals} onItemClick={(item, positionY) => onItemClick(item, positionY, 1)} title={'Города'}/>   
      
      { activeEvent && (
          <MyModal 
            visible={activeEvent} 
            onClose={handleCancel} 
            positionY={modalPositionY} 
            positionX={modalPositionX} 
          >
            {<h3>{Number(activeEvent.year || activeEvent.startYear) > 0 ? `${activeEvent.year || activeEvent.startYear} г.`: `${activeEvent.year || activeEvent.startYear} г. (до Н.Э.)`}</h3>}
            <div className="card-header">
              <h3 className="card-title">{activeEvent.title || activeEvent.name}</h3>                
            </div>
            <br/>
            <p className="card-description">{activeEvent.description}</p>
            <br/>
            {activeEvent.tags && (
              <div className="card-tags">
                {activeEvent.tags.map((tag, i) => (
                  <span key={i} className="tag">{tag}</span>
                ))}
              </div>
            )}
            {activeEvent.casualties && (
              <div className="card-casualties">
                💀 Потери: {activeEvent.casualties}
              </div>
            )}
            <br/>
            <button className="close-btn" onClick={handleCancel}>
              Ок
            </button>
            <br/>
        </MyModal>
      )}
    </div>
    </>
  );
}

export default AppRussian;